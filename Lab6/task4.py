import time
from google import genai

client = genai.Client(api_key="API_KEY")  
MODEL_LLM = "gemini-3.5-flash-lite"


def classify_few_shot(text: str):
    prompt = f"""Класифікуй наведений текст за однією з категорій: програмування, штучний інтелект, бази даних, комп'ютерні мережі.
Поверни лише назву категорії.

Текст: Python є мовою програмування високого рівня з динамічною типізацією.
Категорія: програмування

Текст: Нейронна мережа складається з набору взаємопов'язаних штучних нейронів для навчання на даних.
Категорія: штучний інтелект

Текст: Реляційна база даних зберігає інформацію у вигляді пов'язаних таблиць і використовує мову SQL.
Категорія: бази даних

Текст: Протокол TCP забезпечує надійну доставку пакетів даних між вузлами в інтернеті.
Категорія: комп'ютерні мережі

Текст: {text}
Категорія:"""

    try:
        response = client.models.generate_content(
            model=MODEL_LLM,
            contents=prompt
        )
        print(f"Відповідь LLM (Імітація Fine-tuning): {response.text.strip()}")
    except Exception as e:
        print(f"Помилка: {e}")


test_texts = [
    "Використання інкапсуляції та поліморфізму дозволяє створювати гнучку архітектуру класів.",
    "Механізм self-attention в архітектурі трансформерів допомагає моделі враховувати контекст слів.",
    "Зовнішні ключі забезпечують цілісність зв'язків між таблицями у реляційних СУБД.",
    "Маршрутизатори визначають оптимальний шлях передачі пакетів між підмережами за IP-адресами.",
    "Згорткові нейронні мережі ефективно виділяють візуальні ознаки для розпізнавання об'єктів на фото.",
    "Принципи ACID гарантують атомарність та надійність виконання транзакцій при збоях."
]

print("ЗАВДАННЯ 4. ІМІТАЦІЯ FINE-TUNING (FEW-SHOT PROMPTING)")
for idx, text in enumerate(test_texts, 1):
    print("\n")
    print(f"Приклад {idx}: {text}")
    classify_few_shot(text)
