from google import genai
from google.genai import types
from task1 import my_tools
from task3 import PLANNING_INSTRUCTION
client = genai.Client(api_key="API_KEY")
MODEL_LLM = "gemini-3.5-flash-lite"

config = types.GenerateContentConfig(
    system_instruction=PLANNING_INSTRUCTION,
    tools=my_tools,
    temperature=0.2
)

agent = client.chats.create(model=MODEL_LLM, config=config)

tests = [
    ("1. Просте питання (без інструмента)", 
     "Що таке рекурсія в програмуванні простими словами?"),
     
    ("2. Задача з інструментом", 
     "Скільки днів залишилося до іспиту 2026-12-20?"),
     
    ("3. Складне завдання (кілька кроків + 2 інструменти)", 
     "Мої бали за тести з дисципліни 'Бази даних': 14, 18, 20, 16. Порахуй середній бал, визнач скільки днів залишилось до іспиту 2026-12-10 і склади короткий план підготовки на цей час."),
     
    ("4.1. Контекст для пам'яті", 
     "Я зараз готуюся до захисту лабораторної роботи з SQL-запитів та індексів у PostgreSQL."),
     
    ("4.2. Запит з використанням пам'яті", 
     "Склади 3 контрольні запитання для самоперевірки за темою моєї лабораторної і порахуй через калькулятор, скільки хвилин піде на підготовку, якщо на кожне питання виділити по 15 хвилин."),
     
    ("5. Перевірка коректності (ділення на нуль)", 
     "Обчисли вираз 50 / 0 за допомогою калькулятора."),
     
    ("Додатково (Завдання 7: обмеження агента)", 
     "Який зараз актуальний курс долара в обмінниках Чернівців?")
]

print("ЗАВДАННЯ 6 ТА 7. ТЕСТУВАННЯ ТА АНАЛІЗ ОБМЕЖЕНЬ")
for name, query in tests:
    print("\n")
    print(f"{name}")
    print(f"Запит: {query}")
    res = agent.send_message(query)
    print(f"Відповідь:\n{res.text}")