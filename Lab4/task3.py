from google import genai

client = genai.Client(api_key="API_KEY")
MODEL = "gemini-3.5-flash-lite"

input_text = """
Пошук у ширину (BFS) використовує чергу (FIFO) та гарантує знаходження найкоротшого шляху у незваженому графі.
Пошук у глибину (DFS) реалізується за допомогою стека (LIFO) або рекурсії та використовує менше пам'яті на графах із великою шириною.
BFS є абсолютно кращим алгоритмом за DFS, і його слід використовувати завжди, оскільки рекурсія в DFS лише псує структуру коду.
Часова складність обох алгоритмів становить O(V + E), де V — кількість вершин, а E — кількість ребер.
"""

prompt_react = f"""
Задача: Проаналізуй наведений текст про алгоритми пошуку на графах (DFS та BFS) та визнач, які твердження є об'єктивними технічними фактами, а які — суб'єктивними висновками чи думками автора.

Виконай це завдання, суворо дотримуючись структури ReAct:
1. ПЛАН ДІЙ: Коротко опиши кроки, які ти виконаєш для аналізу тексту.
2. ВИКОНАННЯ (Thought/Action): Проаналізуй кожне речення з тексту та класифікуй його.
3. ПЕРЕВІРКА: Оціни власні висновки на наявність помилок чи упереджень.
4. ПІДСУМКОВИЙ РЕЗУЛЬТАТ: Надай підсумкову таблицю з розділеними фактами та суб'єктивними думками.

Текст для аналізу:
{input_text}
"""

interaction_react = client.interactions.create(
    model=MODEL,
    input=prompt_react
)

print("ІМІТАЦІЯ ReAct (DFS vs BFS)")
print(interaction_react.output_text)