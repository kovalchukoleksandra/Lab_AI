from google import genai

client = genai.Client(api_key="API_KEY")
MODEL = "gemini-3.5-flash-lite"

text_to_analyze = """
Штучний інтелект стає ключовим інструментом у сфері кібербезпеки. 
Сучасні алгоритми машинного навчання здатні аналізувати мільйони подій у реальному часі, 
виявляти аномалії та блокувати кібератаки ще до їх поширення. 
Проте ця технологія є зброєю обопільного гостріння. Зловмисники також використовують 
ШІ для створення переконливих фішингових розсилок, генерації шкідливого коду та 
автоматизації пошуку вразливостей у системних мережах. 
Тому забезпечення безпеки вимагає постійного оновлення методів захисту та людського контролю.
"""

prompt_1 = f"""
Проаналізуй наведений текст та визнач його основні ідеї:

{text_to_analyze}
"""

interaction_1 = client.interactions.create(
    model=MODEL,
    input=prompt_1
)

print("ЗВИЧАЙНИЙ PROMPT")
print(interaction_1.output_text)

prompt_2 = f"""
Ти провідний аналітик із кібербезпеки. Проаналізуй наданий текст.

Виконай завдання поетапно:
1. Визнач головну тему тексту одним реченням.
2. Виділи 3 ключові ідеї.
3. Окремо наведи переваги використання ШІ та загрози.
4. Сформулюй короткий висновок (до 30 слів).

Результат подай структуровано у вигляді маркованого списку.

Текст:
{text_to_analyze}
"""

interaction_2 = client.interactions.create(
    model=MODEL,
    input=prompt_2
)

print("\nПРОСУНУТИЙ PROMPT")
print(interaction_2.output_text)