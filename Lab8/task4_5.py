import time
from agents import (
    PLANNER_INSTRUCTION,
    EXECUTOR_INSTRUCTION,
    REVIEWER_INSTRUCTION,
    run_agent
)

def analyze_text(text: str):
    planner_prompt = f"Склади план аналізу для наступного тексту:\n\n{text}"
    plan = run_agent(PLANNER_INSTRUCTION, planner_prompt, temperature=0.2)

    executor_prompt = (
        f"Ось план дій від планувальника:\n{plan}\n\n"
        f"Виконай аналіз для цього тексту:\n{text}"
    )
    draft_analysis = run_agent(EXECUTOR_INSTRUCTION, executor_prompt, temperature=0.2)

    reviewer_prompt = (
        f"ОРИГІНАЛЬНИЙ ТЕКСТ:\n{text}\n\n"
        f"ЧЕРНЕТКА АНАЛІЗУ ВІД ВИКОНАВЦЯ:\n{draft_analysis}\n\n"
        f"Перевір коректність та сформуй фінальну відповідь."
    )
    final_output = run_agent(REVIEWER_INSTRUCTION, reviewer_prompt, temperature=0.1)
    
    return plan, draft_analysis, final_output

