from google import genai
client = genai.Client(api_key="API_KEY")
MODEL = "gemini-3.5-flash-lite"

prompt_zero_shot = """
Поясни, як штучний інтелект використовується
у повсякденному житті людини.
Наведи 4 приклади його застосування в побуті
та коротко опиши кожен із них.
Використовуй прості та зрозумілі слова.
"""

interaction_zero_shot = client.interactions.create(
    model=MODEL,
    input=prompt_zero_shot
)

print("ZERO-SHOT PROMPT")
print(interaction_zero_shot.output_text)

